// ABOUTME: HTML escaping shared by the app's string-template renderers.
// ABOUTME: Safe for element content and for quoted attribute values.

export function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
